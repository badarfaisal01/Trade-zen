<?php
/**
 * Diagnostic: Identify why charts show a vertical drop + straight line
 * for Forex pairs like EURUSD, USDJPY, USDCAD
 */
require dirname(__DIR__) . '/app/bootstrap.php';

$symbols = ['EURUSD', 'USDJPY', 'USDCAD', 'GBPUSD'];
$nowMs = (int)floor(microtime(true) * 1000);

echo "=== STRAIGHT LINE DIAGNOSTIC ===\n";
echo "Current time: " . gmdate('Y-m-d H:i:s', (int)($nowMs/1000)) . " UTC\n";
echo "Current time: " . date('Y-m-d H:i:s', (int)($nowMs/1000)) . " Local\n\n";

foreach ($symbols as $symbol) {
    echo "--- $symbol ---\n";
    
    $asset = market_asset($symbol, false);
    if (!$asset) {
        echo "  ERROR: Asset not found in DB\n\n";
        continue;
    }
    
    echo "  DB base_price: " . ($asset['base_price'] ?? 'NULL') . "\n";
    echo "  DB decimal_places: " . ($asset['decimal_places'] ?? 'NULL') . "\n";
    echo "  DB api_symbol: " . ($asset['api_symbol'] ?? 'NULL') . "\n";
    echo "  DB price_source: " . ($asset['price_source'] ?? 'NULL') . "\n";
    echo "  DB category: " . ($asset['category'] ?? 'NULL') . "\n";
    echo "  is_active: " . ($asset['is_active'] ?? 'NULL') . "\n";
    
    // Check market status
    $status = market_status($asset, $nowMs);
    echo "  Market status: " . ($status['isOpen'] ? 'OPEN' : 'CLOSED') . "\n";
    echo "  Reason: " . ($status['reason'] ?? '-') . "\n";
    if (!$status['isOpen']) {
        echo "  Closed at: " . gmdate('Y-m-d H:i:s', (int)($status['closedAt']/1000)) . " UTC\n";
        echo "  Closed price: " . $status['closedPrice'] . "\n";
        echo "  Next open: " . ($status['nextOpenAt'] ? gmdate('Y-m-d H:i:s', (int)($status['nextOpenAt']/1000)) . " UTC" : '-') . "\n";
    }
    
    // Get live price
    $livePrice = market_price_at($asset, $nowMs, true);
    echo "  market_price_at (now, no bias): " . $livePrice . "\n";
    
    // Get price at closedAt time  
    if (!$status['isOpen'] && $status['closedAt']) {
        $priceAtClose = market_price_at($asset, (int)$status['closedAt'], true);
        echo "  market_price_at (closedAt, no bias): " . $priceAtClose . "\n";
    }
    
    // Fetch a few candles to compare
    try {
        $candles = market_candles($asset, 60, 10, $nowMs);
        $lastCandle = end($candles);
        $firstCandle = reset($candles);
        echo "  Candle count: " . count($candles) . "\n";
        if ($firstCandle) {
            echo "  First candle time: " . gmdate('H:i:s', (int)($firstCandle['time']/1000)) . " UTC, close=" . $firstCandle['close'] . "\n";
        }
        if ($lastCandle) {
            echo "  Last candle time: " . gmdate('H:i:s', (int)($lastCandle['time']/1000)) . " UTC, close=" . $lastCandle['close'] . "\n";
        }
        
        // Check price gap between last candle close and closedPrice/livePrice
        $effectiveTargetPrice = $status['isOpen'] ? $livePrice : (float)$status['closedPrice'];
        $gap = abs($effectiveTargetPrice - (float)$lastCandle['close']);
        $gapPct = (float)$lastCandle['close'] > 0 ? ($gap / (float)$lastCandle['close'] * 100) : 0;
        echo "  Target price (used as live): " . $effectiveTargetPrice . "\n";
        echo "  GAP between last candle close and target: " . $gap . " (" . number_format($gapPct, 4) . "%)\n";
        
        if ($gapPct > 0.05) {
            echo "  *** WARNING: Price gap > 0.05% - will cause visible spike! ***\n";
        }
    } catch (Throwable $e) {
        echo "  Candle error: " . $e->getMessage() . "\n";
    }
    
    // Check market_reference_price vs candle data
    $refPrice = market_reference_price($asset);
    echo "  market_reference_price: " . $refPrice . "\n";
    
    // Check TwelveData price
    $tdKey = (string)env('TWELVEDATA_API_KEY', '');
    if ($tdKey) {
        $apiSym = trim((string)($asset['api_symbol'] ?? $asset['symbol'] ?? ''));
        try {
            $tdPrice = fetch_twelvedata_price($apiSym, $tdKey);
            echo "  TwelveData live price: " . $tdPrice . "\n";
        } catch (Throwable $e) {
            echo "  TwelveData price error: " . $e->getMessage() . "\n";
        }
    }
    
    echo "\n";
}

echo "\n=== KEY ANALYSIS ===\n";
echo "If closedPrice differs significantly from last candle close, the chart will show a vertical spike.\n";
echo "This happens because closedPrice is generated by market_price_at() (deterministic math)\n";
echo "while candle data may come from TwelveData API (real market data).\n";
echo "These two sources can produce very different prices.\n";
